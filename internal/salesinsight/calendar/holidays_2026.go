// DataVersion 是本表覆盖的年份，便于后台显示与告警。
//
// ⚠️ 它的用途是**主动告警**而不是自动判断：
// 一旦系统日期进入未覆盖的年份（例如 2027-01-01 到来而表还没更新），
// 日报会开始缺少节假日上下文。此时应该在卡片或 healthz 上提示
// "节假日数据待更新"，而不是静默用朴素判定继续跑 —
// 后者会让 2027 年春节的每一份日报都缺少最重要的解释维度。
const DataVersion = "2026"

// CoverageEnd 是本表保证完整的最后一天（= 2026 国庆假期结束日）。
const CoverageEnd = "2026-10-07"

// AddHolidays 追加法定假日。用于年度更新工具。
func AddHolidays(m map[string][]string) { for k, v := range m { holidays[k] = v } }

// AddMakeupWorkdays 追加调休上班日。用于年度更新工具。
func AddMakeupWorkdays(m map[string][]string) { for k, v := range m { makeupWorkdays[k] = v } }

// KnownYears 返回本表覆盖的年份集合（用于自检与后台展示）。
func KnownYears() []string {
	seen := map[string]bool{}
	for d := range holidays {
		if len(d) >= 4 {
			seen[d[:4]] = true
		}
	}
	out := make([]string, 0, len(seen))
	for y := range seen {
		out = append(out, y)
	}
	return out
}
